// REGRESSION LIVE (6 TC): proposal feature must not break existing modules
import fs from "fs";
import { env, Rest, login, uuid } from "./live-lib.mjs";
const authed = await login().then(s=>new Rest(s.accessToken));
const anon = new Rest(env.VITE_SUPABASE_ANON_KEY);
const results=[]; const rec=(id,n,st,d)=>{results.push({id,name:n,status:st,detail:d});console.log(`${st==="PASS"?"✅":st==="FINDING"?"🔎":"❌"} ${id} ${n} :: ${String(d).slice(0,170)}`);};
const S=await login(); const USER=S.userId;
const wsList=(await authed.select("companies","select=id,name,owner_id&deleted_at=is.null")).json;
const WS=wsList.find(w=>w.owner_id===USER)||wsList[0];
const CLIENT=((await authed.select("clients",`company_id=eq.${WS.id}&limit=1`)).json)[0];
const BANK=((await authed.select("bank_accounts",`company_id=eq.${WS.id}&limit=1`)).json)[0];

try{
  // REG-01 fetchWorkspace (Invoices/Dashboard/Clients page loader) still works after proposal tables added
  const [c,b,i]=await Promise.all([
    authed.select("clients",`company_id=eq.${WS.id}&order=created_at.asc`),
    authed.select("bank_accounts",`company_id=eq.${WS.id}&order=created_at.asc`),
    authed.select("invoices",`company_id=eq.${WS.id}&order=created_at.asc`)]);
  rec("REG-01","fetchWorkspace queries (clients/banks/invoices) unaffected", c.ok&&b.ok&&i.ok?"PASS":"FAIL", `clients=${c.json?.length} banks=${b.json?.length} invoices=${i.json?.length}`);

  // REG-02 Invoices list includes DP invoice generated by earlier CP run? create one via full flow then check invoice readback shape used by mapInvoice
  const token=uuid();
  const ins=await authed.insert("proposals",{agency_id:USER,company_id:WS.id,client_id:CLIENT?.id,token,title:"SIT-REG lifecycle",
    client_name:CLIENT?.name,client_email:CLIENT?.email,base_price:4000000,dp_percentage:50,status:"SENT",
    payment_bank_account_id:BANK?.id,payment_bank_name:BANK?.name,payment_account_number:BANK?.account_number,payment_account_holder:BANK?.holder,
    agency_whatsapp_number:"628123",total_amount:4000000,dp_amount:2000000});
  const p=ins.json[0];
  const sig=`${env.VITE_SUPABASE_URL}/storage/v1/object/public/proposal-assets/signatures/${token}/signature.png`;
  const ap=await anon.rpc("respond_to_proposal",{p_token:token,p_response:"APPROVED",p_selected_addon_ids:[],p_signature_url:sig});
  if(ap.json?.ok){
    const inv=(await authed.select("invoices",`id=eq.${ap.json.invoice_id}&select=*`)).json[0];
    const shape=["id","number","client_snapshot","project_name","invoice_date","due_date","items","status","bank_snapshot"].every(k=>k in inv);
    rec("REG-02","DP invoice row compatible with existing invoice mapper/fields", shape&&inv.status==="PENDING"?"PASS":"FAIL", `num=${inv?.number} keys_missing=${shape?0:Object(["id","number","client_id","tax_rate","discount","notes"]).filter(k=>!(k in inv))}`);
    // REG-03 public invoice link for DP invoice (get_public_invoice via share_link_generated_at set by converter)
    const pub=await anon.rpc("get_public_invoice",{p_id:ap.json.invoice_id});
    rec("REG-03","PublicInvoice RPC reads DP invoice (share link works)", pub.ok&&pub.json?"PASS":"FAIL", `HTTP ${pub.status} hasInv=${!!pub.json?.invoice||!!pub.json} snippet=${JSON.stringify(pub.json).slice(0,80)}`);
    // REG-04 company lastSequence bumped & manual invoice numbering unaffected
    const comp=(await authed.select("companies",`id=eq.${WS.id}&select=styling`)).json[0];
    const seq=comp.styling?.settings?.lastSequence;
    rec("REG-04","companies.styling.settings.lastSequence bumped (shared counter with manual invoices)", typeof seq==="number"&&seq>=1?"PASS":"FAIL", `lastSequence=${seq}`);
    // sequence continuity: numbers unique per company
    const nums=(await authed.select("invoices",`company_id=eq.${WS.id}&select=number&order=created_at.desc&limit=50`)).json.map(x=>x.number);
    rec("REG-04b","No duplicate invoice numbers in workspace", new Set(nums).size===nums.length?"PASS":"FAIL", `n=${nums.length} uniq=${new Set(nums).size}`);
    // cleanup this lifecycle pair
    await authed.del("proposals",`id=eq.${p.id}`);
    const d=await authed.del("invoices",`id=eq.${ap.json.invoice_id}`);
    console.log(`cleanup proposal+invoice HTTP ${d.status}`);
  } else rec("REG-02","approve setup failed","FAIL",JSON.stringify(ap.json).slice(0,120));

  // REG-05 Clients module: deleting a client referenced by proposal -> SET NULL, no crash
  const tmpClient=await authed.insert("clients",{company_id:WS.id,name:"SIT-REG delme",email:"regdel@x.local"});
  const tc=tmpClient.json?.[0];
  if(tc){
    const t2=uuid();
    const p2=await authed.insert("proposals",{agency_id:USER,company_id:WS.id,client_id:tc.id,token:t2,title:"SIT-REG clientdel",
      client_name:"X",client_email:"x@x.local",base_price:1,dp_percentage:50,status:"DRAFT",payment_bank_account_id:BANK?.id,payment_bank_name:BANK?.name,payment_account_number:BANK?.account_number,payment_account_holder:BANK?.holder,agency_whatsapp_number:"628",total_amount:1,dp_amount:0.5});
    const dc=await authed.del("clients",`id=eq.${tc.id}`);
    const chk=dc.ok?(await authed.select("proposals",`id=eq.${p2.json[0].id}&select=client_id`)).json[0]:null;
    rec("REG-05","Delete referenced client -> proposal.client_id SET NULL (no FK error)","INFO", dc.ok? `client deleted, proposal.client_id=${chk?.client_id}` : `client delete blocked: ${dc.text.slice(0,100)}`);
    if(p2.json?.[0]) await authed.del("proposals",`id=eq.${p2.json[0].id}`);
  } else rec("REG-05","client seed failed","BLOCKED",tmpClient.text.slice(0,100));

  // REG-06 dead enum states PAID/EXPIRED accepted by DB but unreachable from app (mirrors PD-09)
  rec("REG-06","PAID/EXPIRED: enum-writable (PD-09 proven), zero code paths set them -> UI badges dead","FINDING","grep src/: only type defs + STATUS_STYLES; respond/update RPC never emit them");

  // REG-07 routing/auth: /proposals* requires session (by-code) & /p/:token public — verify anon REST/RPC boundary once more
  const anonRpcOk=await anon.rpc("get_public_proposal",{p_token:uuid()});
  const anonTable=await anon.select("proposals","select=id&limit=1");
  rec("REG-07","Public path uses SECURITY DEFINER RPC (works anon); direct table read blocked", anonRpcOk.status===200&&!anonTable.ok?"PASS":"FAIL", `rpc=${anonRpcOk.status} table=${anonTable.status}`);
}catch(e){rec("REG-RUN","harness error","FAIL",e.message);}
finally{
  const left=(await authed.select("proposals","title=like.SIT-REG*&select=id")).json;
  const li=(await authed.select("invoices","project_name=like.SIT-REG*&select=id,number")).json;
  console.log("leftover proposals:",left.length,"invoices:",JSON.stringify(li));
  const pass=results.filter(r=>r.status==="PASS").length;
  console.log(`\nTOTAL ${results.length} | PASS ${pass} | FAIL ${results.filter(r=>r.status==="FAIL").length} | OTHER ${results.length-pass-results.filter(r=>r.status==="FAIL").length}`);
  fs.writeFileSync(new URL("./REG-live-report.json",import.meta.url),JSON.stringify(results,null,1));
}
